#!/usr/bin/env bash
# Physical device: Release + embedded JS (Debug + ENABLE_DEBUG_DYLIB crashes RN on device).
set -euo pipefail
ROOT="$(cd "$(dirname "$0")/.." && pwd)"
cd "$ROOT"

SCHEME="${IOS_SCHEME:-SplitKeys}"
USER_ARGS=("$@")

write_packager_env() {
  local ip=""
  for iface in en0 en1 bridge0; do
    ip="$(ipconfig getifaddr "$iface" 2>/dev/null || true)"
    [[ -n "$ip" ]] && break
  done
  {
    echo "# Auto-generated by scripts/ios-run.sh"
    [[ -n "$ip" ]] && echo "export REACT_NATIVE_PACKAGER_HOSTNAME=${ip}"
    echo "export FORCE_BUNDLING=1"
  } > "$ROOT/ios/.xcode.env.local"
  if [[ -n "$ip" ]]; then
    echo "→ Device Metro (optional): http://${ip}:8081"
  fi
}

run_ios() {
  local -a args=(--scheme "$SCHEME")
  args+=("$@")
  if ((${#USER_ARGS[@]})); then
    exec npx react-native run-ios "${args[@]}" "${USER_ARGS[@]}"
  fi
  exec npx react-native run-ios "${args[@]}"
}

physical_udid() {
  xcrun devicectl list devices 2>/dev/null \
    | grep -E 'physical' \
    | grep -oE '[0-9A-Fa-f]{8}-[0-9A-Fa-f]{16}' \
    | head -1
}

UDID="$(physical_udid || true)"

if [[ -n "$UDID" ]]; then
  echo "→ Installing on physical device ($UDID) [Release — stable on hardware]"
  write_packager_env
  (cd "$ROOT/ios" && bundle exec pod install >/dev/null)
  run_ios --device "$UDID" --mode Release
fi

SIM="${IOS_SIMULATOR:-iPhone 16}"
echo "→ No physical device; simulator \"$SIM\" [Debug]"
run_ios --simulator "$SIM"
